-- Mysvex shared product catalogue and coupons.
-- Run this in Supabase SQL Editor for the same project configured in supabase-config.js.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  category text not null default 'earrings',
  img text,
  description text,
  metal text,
  weight text,
  stone text,
  discount_percent numeric(5,2) not null default 0 check (discount_percent >= 0 and discount_percent <= 100)
);

alter table public.products add column if not exists created_at timestamptz not null default now();
alter table public.products add column if not exists name text;
alter table public.products add column if not exists price numeric(12,2) not null default 0;
alter table public.products add column if not exists category text not null default 'earrings';
alter table public.products add column if not exists img text;
alter table public.products add column if not exists description text;
alter table public.products add column if not exists metal text;
alter table public.products add column if not exists weight text;
alter table public.products add column if not exists stone text;
alter table public.products add column if not exists discount_percent numeric(5,2) not null default 0;

create table if not exists public.coupons (
  code text primary key,
  percent integer not null check (percent between 1 and 100),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.coupons enable row level security;

drop policy if exists "Public can read products" on public.products;
create policy "Public can read products" on public.products for select to anon, authenticated using (true);

drop policy if exists "Admins insert products" on public.products;
create policy "Admins insert products" on public.products for insert to authenticated with check (public.is_admin());

drop policy if exists "Admins update products" on public.products;
create policy "Admins update products" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins delete products" on public.products;
create policy "Admins delete products" on public.products for delete to authenticated using (public.is_admin());

drop policy if exists "Public can read active coupons" on public.coupons;
create policy "Public can read active coupons" on public.coupons for select to anon, authenticated using (active = true or public.is_admin());

drop policy if exists "Admins insert coupons" on public.coupons;
create policy "Admins insert coupons" on public.coupons for insert to authenticated with check (public.is_admin());

drop policy if exists "Admins update coupons" on public.coupons;
create policy "Admins update coupons" on public.coupons for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins delete coupons" on public.coupons;
create policy "Admins delete coupons" on public.coupons for delete to authenticated using (public.is_admin());

-- Enable realtime so an open storefront updates when admin changes products/coupons.
do $$ begin
  alter publication supabase_realtime add table public.products;
exception when duplicate_object then null;
when undefined_object then raise notice 'supabase_realtime publication was not found; enable Realtime for products and coupons in the dashboard.';
end $$;
do $$ begin
  alter publication supabase_realtime add table public.coupons;
exception when duplicate_object then null;
when undefined_object then raise notice 'supabase_realtime publication was not found; enable Realtime for coupons in the dashboard.';
end $$;
