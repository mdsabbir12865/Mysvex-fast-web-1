-- Mysvex safe, additive migration. Does NOT drop tables or existing data.
-- Review first, then run in Supabase SQL Editor.

begin;

-- Add order fields needed by the website while preserving existing rows.
alter table public.orders
  add column if not exists customer_name text,
  add column if not exists customer_phone text,
  add column if not exists delivery_address text,
  add column if not exists total_amount numeric(12,2),
  add column if not exists items jsonb not null default '[]'::jsonb,
  add column if not exists updated_at timestamptz not null default now();

-- Keep a durable audit trail of order creation/status changes.
create table if not exists public.order_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete restrict,
  user_id uuid,
  old_status text,
  new_status text not null,
  changed_by uuid,
  changed_at timestamptz not null default now()
);

alter table public.order_history enable row level security;

-- A client can read history only for their own orders; admins can read all.
drop policy if exists "Clients read own order history or admins read all" on public.order_history;
create policy "Clients read own order history or admins read all"
  on public.order_history for select to authenticated
  using (
    (user_id = (select auth.uid()))
    or (select public.is_admin())
  );

-- History writes happen through a trigger, not direct client inserts.
drop policy if exists "No direct order history writes" on public.order_history;
create policy "No direct order history writes"
  on public.order_history for insert to authenticated
  with check (false);

create or replace function public.mysvex_log_order_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if TG_OP = 'INSERT' then
    insert into public.order_history(order_id, user_id, old_status, new_status, changed_by)
    values (new.id, new.user_id, null, new.status, auth.uid());
    return new;
  elsif TG_OP = 'UPDATE' and new.status is distinct from old.status then
    new.updated_at := now();
    insert into public.order_history(order_id, user_id, old_status, new_status, changed_by)
    values (new.id, new.user_id, old.status, new.status, auth.uid());
    return new;
  end if;
  return new;
end;
$$;

 drop trigger if exists mysvex_order_history_after_insert on public.orders;
 create trigger mysvex_order_history_after_insert
   after insert on public.orders
   for each row execute function public.mysvex_log_order_history();

 drop trigger if exists mysvex_order_history_after_status_update on public.orders;
 create trigger mysvex_order_history_after_status_update
   before update of status on public.orders
   for each row execute function public.mysvex_log_order_history();

commit;

